# frozen_string_literal: true

# Decides which defs exist and which files they become: the defs reachable
# from the x-method roots, each def's file path and name, and the alias pass.
module TypeGenerator::Plan
  extend self

  def files(schema, unstable_schema = nil)
    defs = schema.fetch('$defs')
    roots = defs.select { |_, definition| definition.key?('x-method') }.keys
    pass = TypeGenerator::Schema.new(defs)
    generated, = generate(pass, roots)
    stable = generated
             .merge(TypeGenerator::ALIASES.to_h { |name, target| alias_file(pass, name, pass.const(target)) })
             .merge(support_files)
             .sort.to_h
    return stable unless unstable_schema

    stable.merge(unstable_files(defs, unstable_schema))
  end

  # The unstable pass generates the defs the stable schema does not already
  # cover: defs unique to the unstable schema and shared defs whose unstable
  # form differs (extra fields or union variants). Identical defs resolve to
  # the stable classes, so the stable namespace is byte-identical whether or
  # not a caller opts in.
  def unstable_files(defs, unstable_schema)
    unstable_defs = unstable_schema.fetch('$defs')
    twins = unstable_defs.reject { |name, definition| defs[name] == definition }.keys
    roots = unstable_defs.select { |_, definition| definition.key?('x-method') }.keys
    schema = TypeGenerator::Schema.new(unstable_defs, header: TypeGenerator::UNSTABLE_HEADER, twins:)
    generated, aliases = generate(schema, roots)
    generated.merge(opt_in_file(generated.keys, aliases))
  end

  # lib/acp/types/unstable.rb is the opt-in: the only entry into
  # lib/acp/types/unstable, which Zeitwerk ignores so nothing loads until a
  # caller requires this file. Aliases are required after the classes they
  # alias: nothing autoloads here, so constant assignment evaluates its target.
  def opt_in_file(paths, aliases)
    classes, alias_files = paths.partition { |path| !aliases.include?(path) }
    requires = [*classes, *alias_files].map { |path| "require_relative '#{path.delete_suffix('.rb')}'" }
    { 'unstable.rb' => <<~RUBY }
      # frozen_string_literal: true

      # Generated by bin/types from schema/schema.unstable.json. Do not edit.
      #
      # Callers opt into the unstable types with `require 'acp/types/unstable'`.
      # Zeitwerk ignores lib/acp/types/unstable, so referencing
      # ACP::Types::Unstable without this require raises NameError.
      # These types are not part of the ACP spec and may change or disappear at
      # any point; the stable ACP::Types namespace is unaffected.

      module ACP::Types::Unstable
      end

      #{requires.join("\n")}
    RUBY
  end

  # One pass's file set: a class file per def a normal edge reaches, an alias
  # file per def a single variant class subsumes — replacing only that def's
  # own class file, since its nested union modules are still referenced — and
  # nothing for a def several variant classes subsume (no single alias target)
  # or that the stable pass already emitted. Returns the files plus the paths
  # of the alias files among them.
  def generate(schema, roots)
    seen = reachable(schema, roots.map { |name| [name, :normal] }, {})
    subsumed = seen.filter_map { |name, status| [name, status.first] if status.is_a?(Array) && status.size == 1 }.to_h
    defs = schema.with_subsumed(subsumed)
    files = seen.flat_map do |name, status|
      next [] unless schema.generated?(name)
      next TypeGenerator::Resolve.definition_files(defs, name) if status == :normal

      kept = TypeGenerator::Resolve.definition_files(defs, name).reject { |path, _| path == path(schema.const(name)) }
      kept.push(alias_file(schema, name, subsumed[name])) if subsumed[name]
      kept
    end.sort.to_h
    aliases = subsumed.filter_map { |name, _| path(schema.const(name)) if schema.generated?(name) }.sort
    [files, aliases]
  end

  # Walks the defs out from the roots, classifying each by how it is reached:
  # :normal keeps its own class, while a subsuming variant option's allOf ref
  # hands the def to the variant classes claiming it — collected as an array
  # of their constants. A def a normal edge also reaches is never subsumed.
  # Traversal continues through subsumed defs: their fields inline into the
  # variant classes, so refs inside them still generate classes.
  def reachable(defs, pending, seen)
    return seen if pending.empty?

    ((name, edge), *rest) = pending
    prior = seen[name]
    return reachable(defs, rest, seen) if prior == :normal
    return reachable(defs, rest, seen.merge(name => edge == :normal ? :normal : prior | edge)) if prior

    reachable(defs, rest + edges(defs, name), seen.merge(name => edge))
  end

  # A def's outgoing edges as [name, edge] pairs: :normal for every ref in
  # the def, and a claimed constant for each def its own variant classes
  # subsume.
  def edges(defs, name)
    definition = defs.fetch(name)
    plain_refs(definition).map { |ref| [ref, :normal] } +
      subsumed_edges(defs, name).map { |ref, variant| [ref, [variant]] }
  end

  # A subsuming option's allOf ref is not a normal edge — the refed def's
  # fields inline into the variant class — but the option's own properties
  # keep theirs.
  def plain_refs(node)
    case node
    when Hash
      node = node.except('allOf') if TypeGenerator::Unions.subsumes_ref?(node)
      node.flat_map { |key, value| key == '$ref' ? [ref_name(value)] : plain_refs(value) }
    when Array then node.flat_map { |value| plain_refs(value) }
    else []
    end
  end

  def subsumed_edges(defs, name)
    union = TypeGenerator::Resolve.union_const(defs, name)
    union ? TypeGenerator::Unions.variant_refs(defs, union, defs.fetch(name)) : []
  end

  def ref_name(ref) = ref.delete_prefix('#/$defs/')

  def path(const)
    "#{const.delete_prefix("#{TypeGenerator::NAMESPACE}::").split('::').map { |part| snake(part) }.join('/')}.rb"
  end

  def snake(name) = name.delete_prefix('_').gsub(/([a-z\d])([A-Z])/, '\1_\2').downcase

  # ParseError and Check are authored here rather than generated from defs:
  # every generated from_h raises and calls them, but the schema has no def
  # that would produce them. Emitted as files so lib/acp/types stays exactly
  # the pipeline's output.
  def support_files
    { 'parse_error.rb' => parse_error_file, 'check.rb' => check_file }
  end

  def parse_error_file
    <<~'RUBY'
      # frozen_string_literal: true

      # Generated by bin/types from schema/schema.json. Do not edit.

      # Raised by the generated from_h when a param does not match its schema
      # type; the connection boundaries rescue it into an invalid-params reply
      # that names the failing path.
      class ACP::Types::ParseError < StandardError
        # @rbs @segments: Array[String | Integer]
        # @rbs @detail: String

        # @rbs segments: Array[String | Integer]
        # @rbs detail: String
        # @rbs return: void
        def initialize(segments, detail)
          @segments = segments.freeze
          @detail = detail
          super("#{path}: #{detail}")
        end

        # @dynamic segments
        attr_reader :segments #: Array[String | Integer]

        # @rbs return: String
        def path
          segments.each_with_index.map do |segment, index|
            if segment.is_a?(Integer) then "[#{segment}]"
            elsif index.zero? then segment
            else ".#{segment}"
            end
          end.join
        end

        # Prepends a container's segments so nested failures report an absolute path.
        #
        # @rbs *segments: (String | Integer)
        # @rbs return: ACP::Types::ParseError
        def prefix(*segments)
          ACP::Types::ParseError.new([*segments, *@segments], @detail)
        end
      end
    RUBY
  end

  def check_file
    <<~'RUBY'
      # frozen_string_literal: true

      # Generated by bin/types from schema/schema.json. Do not edit.

      # The guards the generated from_h methods call. Each takes the fetched value
      # and the path to it, and raises ParseError naming that path when the value
      # does not match the schema type. Nested from_h failures come back with the
      # field path prepended, so the reported path is absolute.
      module ACP::Types::Check
        # @rbs hash: Hash[String, untyped]
        # @rbs key: String
        # @rbs return: untyped
        def self.key(hash, key)
          hash.fetch(key)
        rescue KeyError
          raise ACP::Types::ParseError.new([key], 'is required')
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.string(value, path, allow_nil: false, allow_unset: false)
          return value if value.is_a?(String) || skipped?(value, allow_nil, allow_unset)

          raise ACP::Types::ParseError.new(segments(path), "expected String, got #{describe(value)}")
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.boolean(value, path, allow_nil: false, allow_unset: false)
          return value if value == true || value == false || skipped?(value, allow_nil, allow_unset)

          raise ACP::Types::ParseError.new(segments(path), "expected boolean, got #{describe(value)}")
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs min: Integer?
        # @rbs max: Integer?
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.integer(value, path, min: nil, max: nil, allow_nil: false, allow_unset: false)
          return value if (value.is_a?(Integer) && within?(value, min, max)) || skipped?(value, allow_nil, allow_unset)

          raise ACP::Types::ParseError.new(segments(path), "expected #{bounded('Integer', min, max)}, got #{describe(value)}")
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs min: Integer?
        # @rbs max: Integer?
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.number(value, path, min: nil, max: nil, allow_nil: false, allow_unset: false)
          return value if (value.is_a?(Numeric) && within?(value, min, max)) || skipped?(value, allow_nil, allow_unset)

          raise ACP::Types::ParseError.new(segments(path), "expected #{bounded('Numeric', min, max)}, got #{describe(value)}")
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs values: Array[untyped]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.enum(value, path, values, allow_nil: false, allow_unset: false)
          return value if values.include?(value) || skipped?(value, allow_nil, allow_unset)

          expected = values.map(&:inspect).join(', ')
          raise ACP::Types::ParseError.new(segments(path), "expected one of #{expected}, got #{describe(value)}")
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs classes: Array[untyped]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs ?&items: (untyped, Array[String | Integer]) -> void
        # @rbs return: untyped
        def self.one_of(value, path, classes, allow_nil: false, allow_unset: false, &items)
          return value if skipped?(value, allow_nil, allow_unset)

          unless classes.any? { |klass| value.is_a?(klass) }
            expected = classes.map(&:name).join(' | ')
            raise ACP::Types::ParseError.new(segments(path), "expected #{expected}, got #{describe(value)}")
          end

          return value unless value.is_a?(Array) && items

          value.each_with_index { |item, index| yield(item, [*segments(path), index]) }
          value
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs &check: (untyped, Array[String | Integer]) -> void
        # @rbs return: untyped
        def self.hash(value, path, allow_nil: false, allow_unset: false, &check)
          return value if skipped?(value, allow_nil, allow_unset)
          raise ACP::Types::ParseError.new(segments(path), "expected object, got #{describe(value)}") unless value.is_a?(Hash)

          parsed = {} #: Hash[String, untyped]
          value.each { |key, item| parsed[key] = yield(item, [*segments(path), key]) }
          parsed
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs &check: (untyped, Array[String | Integer]) -> void
        # @rbs return: untyped
        def self.array(value, path, allow_nil: false, allow_unset: false, &check)
          return value if skipped?(value, allow_nil, allow_unset)
          raise ACP::Types::ParseError.new(segments(path), "expected array, got #{describe(value)}") unless value.is_a?(Array)

          value.each_with_index.map { |item, index| yield(item, [*segments(path), index]) }
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs klass: untyped
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.object(value, path, klass, allow_nil: false, allow_unset: false)
          return value if skipped?(value, allow_nil, allow_unset)
          raise ACP::Types::ParseError.new(segments(path), "expected object, got #{describe(value)}") unless value.is_a?(Hash)

          begin
            klass.from_h(value)
          rescue ACP::Types::ParseError => e
            raise e.prefix(*segments(path))
          end
        end

        # @rbs value: untyped
        # @rbs path: String | Array[String | Integer]
        # @rbs klass: untyped
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: untyped
        def self.objects(value, path, klass, allow_nil: false, allow_unset: false)
          return value if skipped?(value, allow_nil, allow_unset)
          raise ACP::Types::ParseError.new(segments(path), "expected array, got #{describe(value)}") unless value.is_a?(Array)

          value.each_with_index do |item, index|
            next if item.is_a?(Hash)

            raise ACP::Types::ParseError.new([*segments(path), index], "expected object, got #{describe(item)}")
          end

          begin
            klass.from_a(value)
          rescue ACP::Types::ParseError => e
            raise e.prefix(*segments(path))
          end
        end

        # @rbs value: untyped
        # @rbs allow_nil: bool
        # @rbs allow_unset: bool
        # @rbs return: bool
        def self.skipped?(value, allow_nil, allow_unset)
          (value.nil? && allow_nil) || (allow_unset && value.equal?(:unset))
        end

        # @rbs path: String | Array[String | Integer]
        # @rbs return: Array[String | Integer]
        def self.segments(path)
          path.is_a?(Array) ? path : [path]
        end

        # @rbs value: untyped
        # @rbs return: String
        def self.describe(value)
          case value
          when nil then 'null'
          when true then 'true'
          when false then 'false'
          else value.class.name
          end
        end

        # @rbs value: Numeric
        # @rbs min: Integer?
        # @rbs max: Integer?
        # @rbs return: bool
        def self.within?(value, min, max)
          (min.nil? || value >= min) && (max.nil? || value <= max)
        end

        # @rbs name: String
        # @rbs min: Integer?
        # @rbs max: Integer?
        # @rbs return: String
        def self.bounded(name, min, max)
          if min && max then "#{name} between #{min} and #{max}"
          elsif min then "#{name} >= #{min}"
          elsif max then "#{name} <= #{max}"
          else name
          end
        end
      end
    RUBY
  end

  def camel(name) = name.split(/[^a-zA-Z\d]/).map(&:capitalize).join

  def alias_file(schema, name, target)
    rbs = "# @rbs!\n#   class #{schema.const(name)} = #{target}\n"
    [path(schema.const(name)), "#{schema.header}\n#{rbs}\n#{schema.const(name)} = #{target}\n"]
  end
end
